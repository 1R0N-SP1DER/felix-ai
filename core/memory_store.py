# ---------- style_profile ----------

def get_style_profile() -> dict | None:
    conn = get_connection()
    row = conn.execute("SELECT * FROM style_profile WHERE id = 1").fetchone()
    conn.close()
    return dict(row) if row else None


def update_style_profile(common_phrases=None, avg_message_length=None,
                          tone_notes=None, formality_level=None):
    """
    Upsert the single style_profile row. Only overwrites fields that are
    explicitly passed (not None), so partial updates don't wipe other fields.
    """
    existing = get_style_profile()
    conn = get_connection()

    if existing is None:
        conn.execute(
            "INSERT INTO style_profile (id, common_phrases, avg_message_length, "
            "tone_notes, formality_level, updated_at) VALUES (1, ?, ?, ?, ?, ?)",
            (
                json.dumps(common_phrases or []),
                avg_message_length,
                tone_notes,
                formality_level,
                _now(),
            ),
        )
    else:
        conn.execute(
            "UPDATE style_profile SET common_phrases = ?, avg_message_length = ?, "
            "tone_notes = ?, formality_level = ?, updated_at = ? WHERE id = 1",
            (
                json.dumps(common_phrases) if common_phrases is not None
                else existing["common_phrases"],
                avg_message_length if avg_message_length is not None
                else existing["avg_message_length"],
                tone_notes if tone_notes is not None else existing["tone_notes"],
                formality_level if formality_level is not None
                else existing["formality_level"],
                _now(),
            ),
        )

    conn.commit()
    conn.close()


