"""
felix-ai Core — memory_store.py
Phase 3: persistent memory layer. Lives on the memory-owner device (phone),
but built/tested on PC first per usual workflow.

Four tables:
  - conversation_log : raw chat history, kept forever, never deleted
  - memories         : smart-detected facts (soft-delete via 'active' flag)
  - rules            : explicit user commands — HIGHEST authority, always
                        override memories/style when assembling prompts
  - style_profile    : single evolving row capturing speech patterns

Smart auto-detection of memories during live conversation is STUBBED here —
real detection is meant to run via Gemini (Phase 5 dependency), so
detect_memory_worthy() currently always returns None. The storage layer
itself is fully functional now, including a bootstrap import path for
pasting in a summary generated by another AI (e.g. ChatGPT) to seed
memory instead of starting cold.
"""

import os
import sqlite3
import json
from pathlib import Path
from datetime import datetime, timezone

DB_PATH = Path(os.environ.get("FELIX_DB") or (Path(__file__).parent / "felix_ai_memory.db"))


def _now() -> str:
    return datetime.now(timezone.utc).isoformat()


def get_connection() -> sqlite3.Connection:
    conn = sqlite3.connect(DB_PATH)
    conn.row_factory = sqlite3.Row
    return conn


def init_db():
    """Create all tables if they don't already exist. Safe to call repeatedly."""
    conn = get_connection()
    cur = conn.cursor()

    cur.execute("""
        CREATE TABLE IF NOT EXISTS conversation_log (
            id INTEGER PRIMARY KEY AUTOINCREMENT,
            timestamp TEXT NOT NULL,
            device TEXT NOT NULL,
            role TEXT NOT NULL,
            content TEXT NOT NULL
        )
    """)

    cur.execute("""
        CREATE TABLE IF NOT EXISTS memories (
            id INTEGER PRIMARY KEY AUTOINCREMENT,
            created_at TEXT NOT NULL,
            updated_at TEXT NOT NULL,
            fact TEXT NOT NULL,
            source TEXT NOT NULL,
            confidence REAL NOT NULL,
            active INTEGER NOT NULL DEFAULT 1,
            category TEXT NOT NULL DEFAULT 'me'
        )
    """)

    # Safe to run repeatedly: adds the category column to a pre-existing
    # memories table that was created before categorization existed.
    try:
        cur.execute("ALTER TABLE memories ADD COLUMN category TEXT NOT NULL DEFAULT 'me'")
    except sqlite3.OperationalError:
        pass  # column already exists

    cur.execute("""
        CREATE TABLE IF NOT EXISTS rules (
            id INTEGER PRIMARY KEY AUTOINCREMENT,
            created_at TEXT NOT NULL,
            rule_text TEXT NOT NULL,
            active INTEGER NOT NULL DEFAULT 1
        )
    """)

    cur.execute("""
        CREATE TABLE IF NOT EXISTS style_profile (
            id INTEGER PRIMARY KEY CHECK (id = 1),
            common_phrases TEXT,
            avg_message_length TEXT,
            tone_notes TEXT,
            formality_level TEXT,
            updated_at TEXT NOT NULL
        )
    """)

    conn.commit()
    conn.close()


# ---------- conversation_log ----------

def log_message(device: str, role: str, content: str):
    """Append one message to the permanent conversation log. Never deleted."""
    conn = get_connection()
    conn.execute(
        "INSERT INTO conversation_log (timestamp, device, role, content) VALUES (?, ?, ?, ?)",
        (_now(), device, role, content),
    )
    conn.commit()
    conn.close()


def search_memories(query: str, limit: int = 5) -> list[dict]:
    """Retrieve top N matching memories using FTS5."""
    conn = get_connection()
    # Note: query string needs to be properly escaped or formatted for FTS5 syntax
    # For now, simplistic approach: match all words
    rows = conn.execute(
        """SELECT m.* FROM memories m
           JOIN memories_fts fts ON m.id = fts.rowid
           WHERE memories_fts MATCH ?
           AND m.active = 1
           ORDER BY rank LIMIT ?""",
        (query, limit)
    ).fetchall()
    conn.close()
    return [dict(row) for row in rows]



# ---------- memories ----------

def add_memory(fact: str, source: str = "stated", confidence: float = 1.0) -> int:
    """
    Add a new memory. source should be 'stated' (user said it directly) or
    'inferred' (smart-detected). Returns the new row's id.
    """
    conn = get_connection()
    now = _now()
    cur = conn.execute(
        "INSERT INTO memories (created_at, updated_at, fact, source, confidence, active) "
        "VALUES (?, ?, ?, ?, ?, 1)",
        (now, now, fact, source, confidence),
    )
    conn.commit()
    new_id = cur.lastrowid
    conn.close()
    return new_id


def get_active_memories() -> list[dict]:
    conn = get_connection()
    rows = conn.execute(
        "SELECT * FROM memories WHERE active = 1 ORDER BY created_at ASC"
    ).fetchall()
    conn.close()
    return [dict(row) for row in rows]


def deactivate_memory(memory_id: int):
    """Soft-delete a memory. We never hard-delete facts — only deactivate them."""
    conn = get_connection()
    conn.execute(
        "UPDATE memories SET active = 0, updated_at = ? WHERE id = ?",
        (_now(), memory_id),
    )
    conn.commit()
    conn.close()


def bootstrap_import_memories(facts: list[str]):
    """
    Bulk-import a list of fact strings, e.g. pasted from a ChatGPT-generated
    summary of Felix. Each becomes its own memory row, source='stated' since
    Felix is the one choosing to import it (even though an AI wrote the
    summary text, Felix is vouching for its accuracy by importing it).
    """
    for fact in facts:
        fact = fact.strip()
        if fact:
            add_memory(fact, source="stated", confidence=1.0)


